    <div id="sub-1">
        <h3>Pemrograman dan <i>coding</i></h3>
        <p>
            Kita sering mendengar kata "pemrograman" dan "<i>coding</i>", tapi
            apasih artinya dan juga beda dari keduanya?
        </p>
        <p>
            Pertama tama <i>coding</i> atau ngoding sendiri adalah aktivitas
            menulis kode dalam sebuah program, seperti
            <i><b>print(Hello, world!)</b></i>. sementara pemrograman sendiri
            adalah proses lengkap dalam membuat sebuah program ataupun
            <i>software</i> itu sendiri yang meliputi merancang, membangun, menguji
            dan juga mempertahankan atau memelihara penuh dari sistem software itu
            sendiri.
        </p>
    </div>
    <div id="sub-2">
        <h3>Bahasa pemrograman</h3>
        <p>
            Sekarang terdapat banyak sekali bahasa pemrograman dimulai dari yang
            mudah dimengerti dan diperuntukan untuk penggunaan lengkap hingga
            bahasa-bahasa receh atau <i>meme language</i> seperti
            <a href="https://en.wikipedia.org/wiki/Brainfuck">brainf*ck</a> (yang
            tidak memiliki tujuan spesifik selain bahan meme atau bercandaan)
        </p>
        <p>
            Bahasa pemrograman sendiri sudah ada sejak lama mulai dari <a
                href="https://fortran-lang.org/">Fortran</a
            > yang menggunakan punchcard di eranya (namun sekarang sudah beralih
            ke text digital) hingga bahasa-bahasa modern seperti C, Python, Java
        </p>
        <p>
            Kenapa terdapat banyak sekali bahasa pemrograman? singkatnya tidak
            ada bahasa pemrograman paling baik, masing masing terdapat kelebihan
            dan kekurangan sendiri seperti C yang bisa berjalan cepat namun
            harus membuat library sendiri untuk fungsi-fungsi yang lebih modern,
            Python yang mudah dimengerti sementara memiliki ekosistem lengkap
            untuk segala kebutuhan dan bidang IT namun berjalan lebih lambat
            dibanding C karna menggunakan <i>interpreter</i>, Java yang meskipun
            bisa berjalan dimana saja namun cenderung memakan memori/RAM yang
            banyak. Dan lebih banyak lagi
        </p>
        <p>
            Banyaknya bahasa pemrograman adalah karena di dunia IT mereka
            digunakan untuk keperluannya masing-masing. C adalah bahasa yang <i
                >low-level</i
            >
            yang sangat cepat dan dapat memanipulasi memori. Python adalah bahasa
            <i>high-level</i> yang memiliki ekosistem luas untuk Sains Data,
            Kecerdasan Artifisial, WebDev, dan lainnya. Java merupakan bahasa
            yang bisa berjalan dimana saja dan merupakan bahasa dari game
            <a href="https://www.minecraft.net/en-us/about-minecraft">
                Minecraft</a
            >
        </p>
        <p>
            Sebagai pemula, banyak orang yang menyarankan Python dikarenakan
            termasuk bahasa high-level dan juga memiliki ekosistem yang luas,
            termasuk di tutorial ini. Namun banyak juga yang menyarankan C
            dikarenakan bahasa tersebut merupakan salah satu bahasa yang akan
            mengajarkan tentang pemrograman yang paling mendasar dari manajemen
            memori dan lain lain. C juga merupakan "ibu" dari banyak bahasa
            pemrograman era sekarang, pada dasarnya bahasa seperti Python
            sendiri memiliki interpreter yang berdasarkan dari C.
        </p>
        <p>
            <b>
                Pada akhirnya, bahasa pemrograman hanyalah sebuah alat
                komprehensif yang bisa digunakan untuk memecahkan masalah atau
                tugas kalian, seperti membuat aplikasi, mengatur database, dan
                tugas ataupun masalah IT lainnya. Bahasa yang mana tergantung
                ekosistem dan fungsi dari bahasa tersebut apakah cocok untuk
                tugasnya atau tidak, di tutorial ini kita akan menggunakan
                Python karena <i>syntax</i>nya yang gampang dimengerti dan
                fleksibel
            </b>
        </p>
    </div>
    <div id="sub-3">
        <h3>Istilah-istilah di pemrograman</h3>
        <p>
            Terdapat beberapa Istilah-Istilah yang sering digunakan di dunia
            pemrograman, diantaranya <i>high/low level</i>,
            <i>interpreter</i>, <i>syntax</i> seperti di bagian atas tadi dan juga
            masih banyak lagi, yang kita akan bahas disini.
        </p>
        <div id="sub-3-1">
        <p><b>1. Syntax</b></p>
        <p>
            Syntax atau Sintaks adalah pola bahasa dari bahasa pemrograman
            tersebut, bisa dikatakan sebagai grammar dari bahasa pemrograman itu
            sendiri
        </p>
        </div>
        <div id="sub-3-2">
        <p><b>2. High-level dan Low-level</b></p>
        <p>
            High-Level disini mengarah kepada bahasa tersebut gampang dipahami
            karna lebih dekat kepada manusia atau pengguna, dan juga cenderung
            tidak memiliki fungsi atau izin lebih tinggi terhadap komputer itu
            sendiri. Sedangkan Low-level mengarah kepada bahasa tersebut lebih
            sulit dipahami dibanding High-level karena lebih dekat kepada sistem
            komputer sendiri dan memiliki izin yang lebih tinggi ke komputer
            seperti manajemen memori langsung.
            <br />
            <b> Bahasa High-level: Python, Java, Javascript </b>
            <br />
            <b>Bahasa Low-level: C, Assembly, Machine code</b>
        </p>
        </div>
        <div id="sub-3-3">
        <p><b>3. Compiler dan Interpreter</b></p>
        <p>
            <i><b>Compiler</b></i> merupakan cara menjalankan program atau
            kodingan dengan mengubah seluruh isi file atau program tersebut
            menjadi sebuah instruksi langsung kepada komputer atau binary.
            Sedangkan <i><b>Interpreter</b></i> adalah cara menjalankan program
            atau kodingan dengan menafsirkan baris per baris di file menjadi
            bahasa mesin tanpa membuat file berisi instruksi komputer atau
            binary
            <br />
            <b>Bahasa yang menggunakan Interpreter: Python, Javascript</b>
            <br />
            <b>Bahasa yang menggunakan Compiler: C, Rust</b>
        </p>
        </div>
        <div id="sub-3-4">
        <p><b>4. Bug dan Debugging</b></p>
        <p>
            <i>Bug</i> bisa diartikan sebagai kesalahan dalam kodingan yang sedang
            dijalankan yang berakibat pada program tersebut error ataupun berjalan
            dengan tidak semestinya, istilah bug sendiri secara harfiah berasal kepada
            bug komputer pertama yaitu sebuah serangga yang masuk ke komputer Harvard
            Mark II pada tanggal 9 September 1947.
        </p>
        <p>
            Debugging adalah istilah yang digunakan untuk aktivitas
            menghilangkan bug atau memperbaiki program yang salah dikarenakan
            bug tersebut.
        </p>
        </div>
        <div id="sub-3-5">
        <p><b>5. IDE dan Code Editor</b></p>
        <p>
            Seseorang bisa menggunakan Code Editor dan juga IDE dalam membuat
            program atau ngoding, namun <b>IDE</b> atau
            <b>Integrated Development Environment</b> dan <b>Code Editor</b> berbeda
            dalam fungsi dan kasus penggunaan
        </p>
        <p>
            <b>Code Editor</b> bisa dianalogikan sebagai ruang dokter dimana masalah
            ringan bisa diselesaikan dengan gampang dan cepat , sama seperti kalau
            ingin membuat program simpel atau project ringan/hobbyist bisa menggunakan
            Code Editor. Yang secara dasar untuk merubah atau mengedit kodingan
        </p>
        <p>
            <b>IDE</b> atau <b>Integrated Development Environment</b> bisa dianalogikan
            sebagai ruang operasi dikarenakan terdapat alat-alat lengkap dan terintegrasi
            untuk masalah yang lebih kompleks dan tindakan yang lebih berat, di IDE
            sendiri tidak hanya memungkinkan untuk mengedit kodingan namun memiliki
            fungsi lain seperti debugger, build tools, database, deployment dan lain
            lain. Sama seperti kalau ingin membuat project besar dan project profesional
            atau kerja.
            <b>Code Editor: VSCode(dasar), Sublime Text, Notepad++, Neovim</b>
            <br />
            <b>IDE: VScode(dengan ekstensi), JetBrains: IntelliJ, PyCharm, CLion, WebStorm</b>
        </p>
        </div>
    </div>
    <div id="sub-4">
        <h3>GitHub</h3>
        <p>
            <b>GitHub</b> adalah platform untuk menyimpan kode program di
            <i>cloud</i> (internet). Bayangkan seperti Google Docs, namun
            khusus untuk kode — kita bisa menulis bersama tim, melihat siapa
            yang mengubah apa, mengembalikan jika ada kesalahan, dan setiap
            anggota tim memiliki salinan yang sama.
        </p>
        <p>
            Selain menyimpan kode, GitHub juga memiliki beberapa fungsi
            penting:
        </p>
        <p>
            <b>Version control</b> — mencatat setiap perubahan kode. Jika
            terjadi kesalahan, kita bisa kembali ke versi sebelumnya seperti
            tombol <i>Undo</i> pada umumnya.
        </p>
        <p>
            <b>Kolaborasi</b> — bekerja bersama tim tanpa khawatir file saling
            tertimpa. Setiap anggota dapat mengerjakan fitur masing-masing,
            kemudian digabungkan menjadi satu.
        </p>
        <p>
            <b>Portfolio</b> — kode yang kita buat akan terlihat di profil
            GitHub, menjadi portofolio langsung bagi perekrut atau siapapun
            yang ingin melihat kemampuan kita.
        </p>
        <p>
            GitHub adalah <b>alat yang wajib</b> dikuasai oleh programmer.
            Tutorial ini sendiri seluruh kodenya di-host di GitHub. Oleh karena
            itu, biasakan diri dari sekarang — buat akun, <i>push</i> project
            kecil-kecilan, dan pelajari <i>Git</i> (program yang menjadi dasar
            dari GitHub).
        </p>
