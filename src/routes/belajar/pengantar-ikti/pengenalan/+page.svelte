        <div id="sub-2">
            <h3>Prospek bidang dan karir</h3>
        <p>
            Profesional di bidang IT memiliki banyak pilihan bidang dan karir
            untuk ditempuh
        </p>
        <p>
            beberapa diantaranya: WebDev, Cloud, DevOps, SysAdmin,
            Cybersecurity, Data Science, Machine Learning
        </p>
        <div id="sub-2-1">
        <p>
            <b>1. WebDev</b> <br />
            <i>Web Development</i> atau Pengembangan Web adalah bidang IT yang
            menekuni pembuatan dan perancangan website, umumnya mereka terbagi
            menjadi 3 yaitu: Frontend, Backend dan Full Stack
            <br />
            <b>Frontend</b> bertugas untuk mengubah design dari seorang UI/UX
            Designer menjadi design website atau aplikasi web yang dibuat, bisa
            juga dibilang kalau mereka ini yang merancang "muka" dari website
            itu sendiri. Seorang Frontend Developer akan fokus pada bagaimana
            website terlihat, bergerak, dan memberikan pengalaman terbaik kepada
            pengguna.
            <br />
            <b>Backend</b> bertugas untuk mengatur dan mengelola urusan belakang
            layar dari website itu sendiri seperti server, API, routing, dan
            lain sebagainya. Backend Developer adalah orang yang bekerja di
            "balik layar" untuk memastikan website dapat berfungsi dengan
            lancar, data tersimpan dengan aman, dan semua logika bisnis berjalan
            sesuai dengan rencana.
            <br />
            <b>Full Stack</b> adalah orang yang mampu melakukan kedua bagian
            tadi yaitu Frontend dan Backend. Mereka memiliki pemahaman
            menyeluruh tentang seluruh ekosistem web development dari user
            interface hingga database dan server management.
            <br />
            <b
                >Bahasa dan alat yang dipakai: HTML-CSS, Javascript, Framework
                Javascript (ReactJS, SvelteJS, ExpressJS, dst.), Database (SQL,
                dst.)</b
            >
        </p>
        </div>

        <div id="sub-2-2">
        <p>
            <b>2. Cloud</b> <br />
            <i>Cloud Computing</i> adalah teknologi yang memungkinkan akses ke
            sumber daya IT seperti server, penyimpanan data, dan aplikasi
            melalui internet tanpa perlu memiliki infrastruktur fisik sendiri.
            Dengan cloud computing, perusahaan tidak perlu lagi berinvestasi
            besar-besaran dalam membeli dan memelihara server fisik mereka
            sendiri, melainkan bisa menyewa layanan dari provider cloud yang
            sudah tersedia.
            <br />
            <b>IaaS (Infrastructure as a Service)</b> menyediakan infrastruktur
            IT seperti server virtual, penyimpanan, dan jaringan yang dapat
            diskalakan sesuai kebutuhan. Dengan IaaS, Anda memiliki kontrol
            penuh atas operating system dan aplikasi yang berjalan di atasnya,
            namun infrastruktur hardware ditangani oleh provider.
            <br />
            <b>PaaS (Platform as a Service)</b> menyediakan platform siap pakai
            untuk mengembangkan, menguji, dan meluncurkan aplikasi tanpa perlu
            mengkhawatirkan infrastruktur yang mendasarinya. Dengan PaaS,
            developer dapat fokus pada coding dan membuat aplikasi, sementara
            semua detail teknis infrastructure dihandle oleh provider.
            <br />
            <b>SaaS (Software as a Service)</b> menyediakan aplikasi siap pakai
            yang dapat diakses melalui browser tanpa perlu instalasi lokal,
            seperti Google Drive, Microsoft 365, dan Salesforce. Pengguna hanya
            perlu membuka aplikasi di browser dan langsung bisa menggunakannya
            tanpa perlu setup atau maintenance yang kompleks.
            <br />
            <b
                >Bahasa dan alat yang dipakai: AWS, Google Cloud Platform (GCP),
                Microsoft Azure, Docker, Kubernetes, Terraform</b
            >
        </p>
        </div>

        <div id="sub-2-3">
        <p>
            <b>3. DevOps</b> <br />
            <i>DevOps</i> adalah kombinasi dari Development dan Operations yang
            fokus pada otomasi, kolaborasi, dan integrasi antara tim pengembang
            (developer) dan tim operasional untuk mempercepat proses deployment
            dan meningkatkan kualitas software. DevOps bukan hanya sekedar tool
            atau teknik, melainkan sebuah budaya dan mindset yang bertujuan
            untuk membuat software development dan deployment menjadi lebih
            efisien dan reliable.
            <br />
            <b>CI/CD (Continuous Integration/Continuous Deployment)</b> adalah
            proses otomatis dimana setiap perubahan code langsung
            diintegrasikan, diuji, dan dideploy ke production tanpa menunggu
            lama. Dengan CI/CD, developer tidak perlu khawatir tentang proses
            deployment yang rumit dan memakan waktu karena semuanya sudah
            diotomasi.
            <br />
            <b>Infrastructure as Code</b> adalah praktik mengelola infrastruktur
            melalui code sehingga lebih mudah di-version control dan
            di-reproduce. Dengan Infrastructure as Code, konfigurasi server dan
            networking dapat didokumentasikan dan di-share seperti halnya code
            aplikasi, sehingga lebih konsisten dan mudah di-maintain.
            <br />
            <b>Monitoring & Logging</b> adalah proses pengawasan aplikasi dan
            infrastruktur untuk mendeteksi masalah lebih awal dan mempercepat
            troubleshooting. DevOps Engineer memastikan bahwa setiap aspek dari
            aplikasi dipantau secara real-time sehingga jika ada masalah, bisa
            langsung ditangani sebelum mempengaruhi user.
            <br />
            <b
                >Bahasa dan alat yang dipakai: Git, Jenkins, GitLab CI, GitHub
                Actions, Docker, Kubernetes, Prometheus, ELK Stack, Ansible</b
            >
        </p>
        </div>

        <div id="sub-2-4">
        <p>
            <b>4. SysAdmin</b> <br />
            <i>System Administrator</i> adalah profesional IT yang bertanggung
            jawab mengelola, memelihara, dan mendukung infrastruktur IT suatu
            organisasi termasuk server, jaringan, database, dan user accounts.
            Sysadmin adalah "manajer" dari seluruh ekosistem IT dalam sebuah
            organisasi, memastikan bahwa semua sistem berjalan lancar dan aman.
            <br />
            <b>Server Management</b> mencakup instalasi, konfigurasi, update,
            dan pemeliharaan server untuk memastikan uptime dan performa
            optimal. Sysadmin harus memastikan bahwa server selalu online,
            responsif, dan memiliki resources yang cukup untuk menangani beban
            kerja yang ada.
            <br />
            <b>User & Access Management</b> meliputi pembuatan user accounts,
            manajemen permissions, dan kontrol akses untuk keamanan sistem.
            Sysadmin mengatur siapa yang bisa mengakses apa, memastikan bahwa
            setiap user memiliki hak akses yang sesuai dengan peran mereka tanpa
            membahayakan keamanan sistem.
            <br />
            <b>Backup & Disaster Recovery</b> adalah strategi untuk melindungi
            data dengan backup reguler dan rencana pemulihan jika terjadi
            bencana. Sysadmin harus memiliki strategi backup yang solid dan plan
            recovery yang terukur sehingga jika terjadi bencana atau kehilangan
            data, bisa di-restore dengan cepat.
            <br />
            <b
                >Bahasa dan alat yang dipakai: Linux/Windows Server, Active
                Directory, Bash/PowerShell, Nagios, Zabbix, Backup tools (Veeam,
                Bacula)</b
            >
        </p>
        </div>

        <div id="sub-2-5">
        <p>
            <b>5. Cybersecurity</b> <br />
            <i>Cybersecurity</i> adalah bidang yang fokus pada perlindungan
            sistem, jaringan, dan data dari ancaman keamanan siber seperti
            hacking, malware, dan serangan cyber lainnya. Di era digital ini,
            cybersecurity menjadi semakin penting karena ancaman cyber terus
            berkembang dan menjadi lebih sophisticated. Seorang cybersecurity
            professional harus selalu update dengan trend attack terbaru dan
            terus mencari cara untuk melindungi organisasi.
            <br />
            <b>Network Security</b> mencakup firewall, intrusion detection, VPN,
            dan teknik lainnya untuk melindungi jaringan dari akses tidak sah.
            Network Security fokus pada layer jaringan untuk memastikan bahwa
            traffic yang masuk dan keluar dari organisasi dipantau dan difilter
            dengan ketat.
            <br />
            <b>Application Security</b> fokus pada keamanan aplikasi terhadap
            vulnerability seperti SQL injection, XSS, dan CSRF melalui secure
            coding practices. Application Security Expert bekerja sama dengan
            developer untuk memastikan bahwa aplikasi yang dibangun sudah aman
            dari common vulnerabilities dan best practices security sudah
            diterapkan.
            <br />
            <b>Incident Response</b> adalah proses mendeteksi, merespons, dan
            pemulihan dari serangan keamanan atau pelanggaran data. Jika terjadi
            security incident, Incident Response Team harus cepat merespons,
            mengidentifikasi masalah, dan melakukan recovery serta remediation
            untuk meminimalkan damage.
            <br />
            <b
                >Bahasa dan alat yang dipakai: Firewall, IDS/IPS, Metasploit,
                Wireshark, Burp Suite, OWASP, Python, SQL</b
            >
        </p>
        </div>

        <div id="sub-2-6">
        <p>
            <b>6. Data Science</b> <br />
            <i>Data Science</i> adalah bidang yang menggunakan metode statistik,
            programming, dan machine learning untuk menganalisis data besar (big
            data) dan mengekstrak insights yang berharga untuk pengambilan
            keputusan bisnis. Data Science adalah bidang yang relatif baru namun
            sangat penting di era big data ini. Seorang data scientist harus
            memiliki kombinasi dari kemampuan programming, statistik, dan
            business acumen.
            <br />
            <b>Data Collection & Cleaning</b> adalah proses mengumpulkan data
            dari berbagai sumber dan membersihkan data untuk memastikan kualitas
            yang baik. Ini adalah tahap yang sangat penting karena quality of
            data akan sangat mempengaruhi hasil analisis dan model nantinya.
            Data Scientist harus teliti dan detail dalam tahap ini.
            <br />
            <b>Exploratory Data Analysis (EDA)</b> adalah teknik untuk
            mengeksplorasi dan memvisualisasikan data guna menemukan pola, tren,
            dan anomali. Melalui EDA, data scientist bisa mendapatkan
            understanding awal tentang data dan formulate hypothesis yang akan
            diuji lebih lanjut.
            <br />
            <b>Predictive Modeling</b> adalah penggunaan algoritma machine
            learning untuk membuat model yang dapat memprediksi nilai atau event
            di masa depan berdasarkan data historis. Dengan predictive modeling,
            bisnis bisa membuat keputusan yang lebih informed dan strategic
            berdasarkan data.
            <br />
            <b
                >Bahasa dan alat yang dipakai: Python, R, SQL, Pandas, NumPy,
                Matplotlib, Seaborn, Tableau, Power BI, Excel</b
            >
        </p>

        <div id="sub-2-7">
        <p>
            <b>7. Machine Learning</b> <br />
            <i>Machine Learning</i> adalah cabang dari Artificial Intelligence
            yang memungkinkan komputer untuk belajar dari data dan membuat
            keputusan atau prediksi tanpa diprogram secara eksplisit untuk
            setiap skenario. Machine Learning adalah teknologi yang sedang hot
            dan banyak aplikasinya di berbagai industri mulai dari healthcare,
            finance, hingga retail.
            <br />
            <b>Supervised Learning</b> adalah pendekatan pembelajaran dengan
            data training yang sudah memiliki label/jawaban, seperti klasifikasi
            dan regresi. Dalam supervised learning, model belajar dari
            contoh-contoh yang sudah memiliki jawaban yang benar, kemudian dapat
            digunakan untuk memprediksi jawaban untuk data baru.
            <br />
            <b>Unsupervised Learning</b> adalah pendekatan pembelajaran dengan
            data yang tidak memiliki label, digunakan untuk menemukan pola atau
            struktur tersembunyi dalam data seperti clustering. Dalam
            unsupervised learning, model harus menemukan sendiri pola dalam data
            tanpa guidance dari label yang sudah ditentukan.
            <br />
            <b>Deep Learning</b> adalah teknik machine learning menggunakan
            neural networks dengan banyak layer untuk menyelesaikan tugas
            kompleks seperti computer vision dan natural language processing.
            Deep Learning adalah breakthrough yang membuat AI menjadi lebih
            powerful dan bisa menyelesaikan task yang sebelumnya dianggap
            mustahil.
            <br />
            <b
                >Bahasa dan alat yang dipakai: Python, TensorFlow, PyTorch,
                Scikit-learn, Keras, OpenCV, NLTK, Jupyter Notebook</b
            >
        </p>
        </div>
